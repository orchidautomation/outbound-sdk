#!/usr/bin/env node

// Writes packages/outbound-sdk/src/insights/inputs.generated.ts: one
// interface per insight input, where every field carries its description,
// default and allowed range as JSDoc. They are read from each insight's Zod
// schema, so the editor hover cannot drift from what the insight accepts.
// The methods on `outbound.insights` take these interfaces.
//
//   node scripts/generate-insight-inputs.mjs          rewrite the file
//   node scripts/generate-insight-inputs.mjs --check  exit 1 if it is stale

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const repositoryRoot = path.resolve(import.meta.dirname, "..");

export const target = path.join(
  repositoryRoot,
  "packages/outbound-sdk/src/insights/inputs.generated.ts"
);

const HEADER = `// Generated by scripts/generate-insight-inputs.mjs from each insight's input
// schema. Do not edit: run \`node scripts/generate-insight-inputs.mjs\`.
//
// What a caller writes to each method on \`outbound.insights\`. A field with a
// default may be left out. Each field's JSDoc gives its default and range.`;

const amount = (value) =>
  Number.isInteger(value) && Math.abs(value) >= 10_000
    ? value.toLocaleString("en-US")
    : String(value);

const literal = (value) => JSON.stringify(value);

/** The TypeScript type of a JSON Schema the way `z.input` writes it. */
export const typeOf = (schema) => {
  if (schema.anyOf !== undefined) {
    return [...new Set(schema.anyOf.map(typeOf))].join(" | ");
  }

  if (schema.enum !== undefined) {
    return schema.enum.map(literal).join(" | ");
  }

  switch (schema.type) {
    case "array": {
      const item = typeOf(schema.items ?? {});

      return item.includes(" | ") ? `(${item})[]` : `${item}[]`;
    }

    case "boolean": {
      return "boolean";
    }

    case "integer":
    case "number": {
      return "number";
    }

    case "null": {
      return "null";
    }

    case "string": {
      return "string";
    }

    default: {
      throw new Error(`No TypeScript type for ${JSON.stringify(schema)}`);
    }
  }
};

// The branches of a schema that is a value or null, without the null.
const valuesOf = (schema) =>
  schema.anyOf === undefined
    ? [schema]
    : schema.anyOf.flatMap(valuesOf).filter((each) => each.type !== "null");

// A bound of a number: `{ exclusive, value }`, or `null` when there is none.
const bound = (inclusive, exclusive) => {
  if (exclusive !== undefined) {
    return { exclusive: true, value: exclusive };
  }

  return inclusive === undefined
    ? null
    : { exclusive: false, value: inclusive };
};

const rangeOf = (schema) => {
  const whole = schema.type === "integer" ? "A whole number" : "A number";
  const low = bound(schema.minimum, schema.exclusiveMinimum);
  const high = bound(schema.maximum, schema.exclusiveMaximum);

  if (low !== null && high !== null && !low.exclusive && !high.exclusive) {
    return `${whole} from ${amount(low.value)} to ${amount(high.value)}.`;
  }

  const parts = [
    low === null
      ? null
      : `${low.exclusive ? "more than " : ""}${amount(low.value)}${low.exclusive ? "" : " or more"}`,
    high === null
      ? null
      : `${high.exclusive ? "less than " : ""}${amount(high.value)}${high.exclusive ? "" : " or less"}`,
  ].filter((part) => part !== null);

  if (parts.length === 0) {
    return schema.type === "integer" ? `${whole}.` : null;
  }

  return `${whole}, ${parts.join(" and ")}.`;
};

const FORMATS = {
  date: "an ISO 8601 date, `YYYY-MM-DD`",
  "date-time": "an ISO 8601 date and time with an offset",
};

/** One sentence per rule the schema holds a value to, besides its type. */
export const rulesOf = (schema) => {
  const values = valuesOf(schema);
  const nullable = values.length !== (schema.anyOf ?? [schema]).length;

  const formats = values.flatMap((each) =>
    each.format === undefined ? [] : [FORMATS[each.format] ?? each.format]
  );

  const rules = values.flatMap((each) => {
    if (each.type === "integer" || each.type === "number") {
      const range = rangeOf(each);

      return range === null ? [] : [range];
    }

    if (each.type === "array") {
      const count =
        each.minItems === undefined
          ? []
          : [
              `At least ${each.minItems} item${each.minItems === 1 ? "" : "s"}.`,
            ];

      const items = each.items?.enum;

      return items === undefined
        ? count
        : [
            ...count,
            `Each one of ${items.map((value) => `\`${value}\``).join(", ")}.`,
          ];
    }

    if (each.type === "string" && each.minLength !== undefined) {
      return each.minLength === 1
        ? ["Not empty."]
        : [`At least ${each.minLength} characters.`];
    }

    return [];
  });

  if (formats.length > 0) {
    const either = [...new Set(formats)].join(", or ");
    rules.unshift(
      `${either[0].toUpperCase()}${either.slice(1)}${nullable ? ", or `null`" : ""}.`
    );
  }

  return rules;
};

const commentOf = (schema, required) => {
  const facts = [
    ...rulesOf(schema),
    required
      ? "Required."
      : `Defaults to \`${JSON.stringify(schema.default ?? null)}\`.`,
  ];

  const lines = [schema.description ?? "", "", facts.join(" ")].filter(
    (line, index) => index !== 1 || schema.description !== undefined
  );

  return ["/**", ...lines.map((line) => ` * ${line}`.trimEnd()), " */"].join(
    "\n"
  );
};

/** The interface body for one insight's input, from its JSON Schema. */
export const renderInput = (parameters) => {
  const required = new Set(parameters.required);

  return Object.entries(parameters.properties ?? {})
    .map(([name, schema]) => {
      const optional = !required.has(name);

      return [
        commentOf(schema, !optional),
        `readonly ${name}${optional ? "?" : ""}: ${typeOf(schema)}${optional ? " | undefined" : ""};`,
      ].join("\n");
    })
    .join("\n\n");
};

/** The whole file, unformatted, for a list of `{ key, name, parameters }`. */
export const renderFile = (insights) =>
  [
    HEADER,
    "",
    "/** The input of every insight, by method name. */",
    "export interface InsightInputs {",
    ...insights.map(
      ({ key, name, parameters }) =>
        `/** The input of \`${key}\` (the \`${name}\` tool). */\nreadonly ${key}: {\n${renderInput(parameters)}\n};`
    ),
    "}",
    "",
  ].join("\n");

const format = (text) =>
  execFileSync(
    path.join(repositoryRoot, "node_modules/.bin/oxfmt"),
    [`--stdin-filepath=${target}`],
    { cwd: repositoryRoot, encoding: "utf-8", input: text }
  );

/** The file as it should be, formatted the way the repository formats it. */
export const generate = async () => {
  const { listInsights } =
    await import("../packages/outbound-sdk/src/insights/index.ts");

  return format(renderFile(listInsights()));
};

/** `true` when the file on disk is what the schemas generate. */
export const isCurrent = async (file = target) =>
  readFileSync(file, "utf-8") === (await generate());

if (process.argv[1] && import.meta.filename === path.resolve(process.argv[1])) {
  if (process.argv.includes("--check")) {
    if (!(await isCurrent())) {
      console.error(
        `${path.relative(repositoryRoot, target)} is stale. Run: node scripts/generate-insight-inputs.mjs`
      );
      process.exitCode = 1;
    }
  } else {
    writeFileSync(target, await generate());
    console.log(`Wrote ${path.relative(repositoryRoot, target)}`);
  }
}
